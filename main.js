var import_obsidian5 = require("obsidian");
var SyncLogModal = class extends import_obsidian5.Modal {
  constructor(app, engine) {
    super(app);
    this.engine = engine;
  }
  onOpen() {
    const { contentEl } = this;
    contentEl.empty();
    contentEl.addClass("baidu-sync-log-modal");
    new import_obsidian5.Setting(contentEl).setName("\u767E\u5EA6\u7F51\u76D8\u540C\u6B65\u65E5\u5FD7").setHeading();
    new import_obsidian5.Setting(contentEl).setName("\u7ACB\u5373\u6267\u884C\u540C\u6B65").setDesc("\u624B\u52A8\u89E6\u53D1\u5168\u91CF\u5BF9\u6BD4\u4E0E\u589E\u91CF\u53CC\u5411\u540C\u6B65").addButton((btn) => {
      btn.setButtonText("\u5F00\u59CB\u540C\u6B65").setCta().onClick(async () => {
        btn.setDisabled(true);
        await this.engine.startSync(false);
        btn.setDisabled(false);
        this.renderLogs(container);
      });
    });
    const container = contentEl.createDiv({ cls: "baidu-sync-log-container" });
    this.renderLogs(container);
  }
  renderLogs(container) {
    container.empty();
    const logs = this.engine.getLogs();
    if (logs.length === 0) {
      container.createEl("p", {
        text: "\u6682\u65E0\u540C\u6B65\u65E5\u5FD7\u8BB0\u5F55",
        cls: "baidu-sync-log-row info"
      });
      return;
    }
    for (const log of logs) {
      const row = container.createDiv({
        cls: `baidu-sync-log-row ${log.level}`
      });
      const timeStr = new Date(log.timestamp).toLocaleTimeString();
      const left = row.createDiv();
      left.createSpan({ text: `[${timeStr}] `, cls: "log-time" });
      left.createSpan({ text: log.message, cls: "log-msg" });
      if (log.detail) {
        row.createDiv({ text: log.detail, cls: "log-detail" });
      }
    }
  }
  onClose() {
    const { contentEl } = this;
    contentEl.empty();
  }
};

// src/main.ts
var BaiduSyncPlugin = class extends import_obsidian6.Plugin {
  constructor() {
    super(...arguments);
    this.settings = DEFAULT_SETTINGS;
    this.intervalId = null;
    this.saveDebounceTimer = null;
    this.ribbonIconEl = null;
  }
  async onload() {
    await this.loadSettings();
    const configDir = this.app.vault.configDir;
    const manifestPath = `${this.manifest.dir || `${configDir}/plugins/baidu-netdisk-sync`}/sync_manifest.json`;
    this.manifestMgr = new ManifestManager(this.app.vault.adapter, manifestPath);
    this.oauth = new BaiduOAuthManager(
      () => this.settings,
      async (s) => {
        this.settings = s;
        await this.saveData(this.settings);
      }
    );
    this.client = new BaiduClient(this.oauth);
    this.engine = new SyncEngine(
      this.app,
      () => this.settings,
      async (s) => {
        this.settings = s;
        await this.saveData(this.settings);
      },
      this.client,
      this.manifestMgr
    );
    const statusBarItem = this.addStatusBarItem();
    this.statusBar = new StatusBarManager(statusBarItem, this.engine, () => {
      new SyncLogModal(this.app, this.engine).open();
    });
    this.ribbonIconEl = this.addRibbonIcon("cloud", "\u767E\u5EA6\u7F51\u76D8\u540C\u6B65", async () => {
      new import_obsidian6.Notice("\u6B63\u5728\u542F\u52A8\u767E\u5EA6\u7F51\u76D8\u540C\u6B65...");
      const res = await this.engine.startSync(false);
      if (res.success) {
        new import_obsidian6.Notice("\u767E\u5EA6\u7F51\u76D8\u540C\u6B65\u5B8C\u6210\uFF01");
      } else {
        new import_obsidian6.Notice("\u767E\u5EA6\u7F51\u76D8\u540C\u6B65\u5931\u8D25\uFF0C\u8BF7\u68C0\u67E5\u540C\u6B65\u65E5\u5FD7");
      }
    });
    this.engine.onStateChange((state) => {
      if (this.ribbonIconEl) {
        if (state === "syncing" || state === "diffing" || state === "preparing") {
          this.ribbonIconEl.addClass("baidu-sync-spinning");
        } else {
          this.ribbonIconEl.removeClass("baidu-sync-spinning");
        }
      }
    });
    this.addCommand({
      id: "baidu-sync-now",
      name: "\u7ACB\u5373\u6267\u884C\u540C\u6B65 (Sync Now)",
      callback: async () => {
        new import_obsidian6.Notice("\u6B63\u5728\u542F\u52A8\u767E\u5EA6\u7F51\u76D8\u540C\u6B65...");
        await this.engine.startSync(false);
      }
    });
    this.addCommand({
      id: "baidu-sync-view-logs",
      name: "\u67E5\u770B\u540C\u6B65\u65E5\u5FD7 (View Sync Logs)",
      callback: () => {
        new SyncLogModal(this.app, this.engine).open();
      }
    });
    this.addSettingTab(new BaiduSyncSettingTab(this.app, this));
    this.setupTriggers();
  }
  onunload() {
    if (this.intervalId !== null) {
      window.clearInterval(this.intervalId);
      this.intervalId = null;
    }
    if (this.saveDebounceTimer !== null) {
      window.clearTimeout(this.saveDebounceTimer);
      this.saveDebounceTimer = null;
    }
  }
  async loadSettings() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
  }
  async saveSettings() {
    await this.saveData(this.settings);
  }
  resetInterval() {
    if (this.intervalId !== null) {
      window.clearInterval(this.intervalId);
      this.intervalId = null;
    }
    if (this.settings.syncIntervalMinutes > 0) {
      const ms = this.settings.syncIntervalMinutes * 60 * 1e3;
      this.intervalId = window.setInterval(async () => {
        if (this.settings.accessToken) {
          await this.engine.startSync(true);
        }
      }, ms);
    }
  }
  setupTriggers() {
    if (this.settings.syncOnStartup && this.settings.accessToken) {
      window.setTimeout(async () => {
        await this.engine.startSync(true);
      }, 3e3);
    }
    this.resetInterval();
    const onVaultChange = (file) => {
      if (!this.settings.syncOnSave || !this.settings.accessToken) return;
      if (this.engine.isSyncing()) return;
      if (file.path.includes("sync_manifest.json") || file.path.includes("workspace")) return;
      if (this.saveDebounceTimer !== null) {
        window.clearTimeout(this.saveDebounceTimer);
      }
      const debounceMs = (this.settings.syncDebounceSeconds || 5) * 1e3;
      this.saveDebounceTimer = window.setTimeout(async () => {
        await this.engine.startSync(true);
      }, debounceMs);
    };
    this.registerEvent(this.app.vault.on("modify", onVaultChange));
    this.registerEvent(this.app.vault.on("create", onVaultChange));
    this.registerEvent(this.app.vault.on("delete", onVaultChange));
  }
};
